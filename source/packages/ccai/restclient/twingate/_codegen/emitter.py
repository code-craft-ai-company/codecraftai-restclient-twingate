__credits__ = []


from typing import Any, Dict, List

from ccai.restclient.twingate._codegen.typemap import (
    python_typename_for_scalar
)


GENERATED_HEADER = (
    '"""\n'
    "    DO NOT EDIT — generated by\n"
    "    python -m ccai.restclient.twingate._codegen.import_schema\n"
    '"""\n'
)


def resolve_type_expression(*, type_ref: Dict[str, Any]) -> str:
    """
        Resolve a GraphQL type reference into an emitted Python type
        expression, applying the ``NON_NULL`` and ``LIST`` wrapping rules.

        :param type_ref: The GraphQL type reference node.

        :returns: The Python type expression string.
    """
    kind = type_ref.get("kind")
    name = type_ref.get("name")
    of_type = type_ref.get("ofType")

    if kind == "NON_NULL":
        # NON_NULL drops the Optional wrapper — emit the inner type bare.
        rtnval = resolve_type_expression(type_ref=of_type)
        return rtnval

    if kind == "LIST":
        inner = resolve_type_expression(type_ref=of_type)
        rtnval = f"List[{inner}]"
        return rtnval

    if kind == "SCALAR":
        rtnval = python_typename_for_scalar(scalar_name=name)
        return rtnval

    if kind == "ENUM":
        rtnval = name
        return rtnval

    if kind == "OBJECT" or kind == "INPUT_OBJECT":
        rtnval = name
        return rtnval

    rtnval = "Any"
    return rtnval


def emit_enum(*, type_node: Dict[str, Any]) -> str:
    """
        Emit Python source for a GraphQL ``ENUM`` type.

        :param type_node: The ``__schema`` type node with ``kind=ENUM``.

        :returns: Python source text for an :class:`enum.Enum` subclass.
    """
    name = type_node.get("name")
    lines: List[str] = [GENERATED_HEADER, "import enum", "", "",
                        f"class {name}(enum.Enum):",
                        f'    """Mirror of the Twingate {name} GraphQL '
                        f'enum."""']

    enum_values = type_node.get("enumValues", [])
    if enum_values is None:
        enum_values = []

    for value_node in enum_values:
        value_name = value_node.get("name")
        lines.append(f'    {value_name} = "{value_name}"')

    lines.append("")
    lines.append(f'__all__ = ["{name}"]')
    lines.append("")

    rtnval = "\n".join(lines)
    return rtnval


def emit_object(*, type_node: Dict[str, Any]) -> str:
    """
        Emit Python source for a GraphQL ``OBJECT`` or ``INPUT_OBJECT``
        type as a :class:`SchemaObject` subclass.

        :param type_node: The ``__schema`` type node.

        :returns: Python source text for a :class:`SchemaObject` subclass.
    """
    name = type_node.get("name")
    lines: List[str] = [
        GENERATED_HEADER,
        "from typing import Any, Dict, List",
        "",
        "from ccai.restclient.base.schemaobject import SchemaObject",
        "from ccai.restclient.base.schemafield import Field",
        "",
        "",
        f"class {name}(SchemaObject):",
        f'    """Mirror of the Twingate {name} GraphQL type."""',
        "",
    ]

    fields = type_node.get("fields")
    if fields is None:
        fields = type_node.get("inputFields", [])
    if fields is None:
        fields = []

    for field_node in fields:
        field_name = field_node.get("name")
        type_ref = field_node.get("type", {})
        type_expr = resolve_type_expression(type_ref=type_ref)
        required = type_ref.get("kind") == "NON_NULL"
        lines.append(
            f"    {field_name}: {type_expr} = Field("
            f"{type_expr!r}, required={required})")

    lines.append("")
    lines.append(f'__all__ = ["{name}"]')
    lines.append("")

    rtnval = "\n".join(lines)
    return rtnval


def emit_schema_modules(*, schema: Dict[str, Any]) -> Dict[str, str]:
    """
        Walk a GraphQL ``__schema`` payload and emit a mapping of module
        file name to Python source text for every non-internal OBJECT,
        INPUT_OBJECT and ENUM type.

        :param schema: The ``__schema`` block of an introspection payload.

        :returns: A mapping of ``<typename-lowercase>.py`` to source text.
    """
    emitted: Dict[str, str] = {}

    types = schema.get("types", [])
    if types is None:
        types = []

    for type_node in types:
        name = type_node.get("name", "")
        kind = type_node.get("kind", "")
        if name.startswith("__"):
            continue

        if kind == "ENUM":
            emitted[f"{name.lower()}.py"] = emit_enum(type_node=type_node)
        elif kind == "OBJECT" or kind == "INPUT_OBJECT":
            emitted[f"{name.lower()}.py"] = emit_object(type_node=type_node)

    rtnval = emitted
    return rtnval


__all__ = [
    "GENERATED_HEADER",
    "resolve_type_expression",
    "emit_enum",
    "emit_object",
    "emit_schema_modules",
]
