"""
    .. module:: emitter
        :platform: Darwin, Linux, Unix, Windows
        :synopsis: Module that contains the schema emitter — walks a GraphQL
                   introspection ``__schema`` payload and produces Python
                   source text for ``SchemaObject`` and ``enum.Enum`` types.

    See the "Codegen Decision" section of ``AGENTS.md``. The emitter is
    retained so a maintainer with a live network can regenerate; the
    checked-in ``model/`` / ``inputs/`` modules were hand-authored from the
    documented Twingate surface because no live network was available at
    build time.

    .. moduleauthor:: Myron Walker <myron.walker@gmail.com>
"""

